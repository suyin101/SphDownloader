package main

import "testing"

func TestNormalizeNumbers(t *testing.T) {
	cases := map[string]string{
		"两名核心五号和十二号都在":      "两名核心5号和12号都在",
		"这一场对比八月和男篮交手换了三个人": "这一场对比8月和男篮交手换了三个人",
		"今晚九点，中国男篮迎战沙特":     "今晚9点，中国男篮迎战沙特",
		"元宝只有五千七百万":         "元宝只有5700万",
		"有三千多万，一下子反超了":      "有3000多万，一下子反超了",
		"慢了九个月到一年":          "慢了9个月到一年",
		"千万别装挡风被":           "千万别装挡风被",
		"这一点十分重要，一点点就行":     "这一点十分重要，一点点就行",
		"增长了百分之三十":          "增长了30%",
		"利率百分之三点五":          "利率3.5%",
		"二零二六年发布":           "2026年发布",
		"第二个对手黎巴嫩":          "第二个对手黎巴嫩",
		"三十岁之前":             "30岁之前",
		"一年一度的粉丝问答":         "一年一度的粉丝问答",
		"两百八十亿美元":           "280亿美元",
		"一千零五元":             "1005元",
		"万一出事了":             "万一出事了",
		"翻了七倍":              "翻了7倍",
		"十一月十五日":            "11月15日",
	}
	for in, want := range cases {
		if got := normalizeNumbers(in); got != want {
			t.Errorf("%s → %s，应该是 %s", in, got, want)
		}
	}
}
